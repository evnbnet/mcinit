package backup

import (
	"testing"

	"github.com/evanb/mcinit/internal/server"
)

func defaultSelection() Selection {
	return NewSelection(server.Info{LevelName: "world"})
}

func TestIncludeRules(t *testing.T) {
	s := defaultSelection()

	tests := []struct {
		rel   string
		isDir bool
		want  bool
		why   string
	}{
		// Worlds, whole.
		{"world", true, true, "the world itself"},
		{"world/level.dat", false, true, "world contents"},
		{"world/region/r.0.0.mca", false, true, "region files are the world"},
		{"world_nether", true, true, "the nether"},
		{"world_the_end", true, true, "the end"},

		// Configuration worth keeping.
		{"server.properties", false, true, "server settings"},
		{"ops.json", false, true, "who is an operator"},
		{"whitelist.json", false, true, "who may join"},
		{"banned-players.json", false, true, "bans"},
		{"bukkit.yml", false, true, "server config"},

		// The jar rule, both sides of it.
		{"paper-1.21.11-132.jar", false, false, "the server jar is re-downloadable"},
		{"purpur-26.3-2655.jar", false, false, "same for purpur"},
		{"plugins/EssentialsX.jar", false, true, "plugin jars cannot be re-downloaded"},
		{"plugins/LuckPerms/config.yml", false, true, "plugin configuration"},
		{"plugins", true, true, "the plugins directory"},

		// Skipped directories.
		{"backups", true, false, "a backup must not contain the other backups"},
		{"backups/2026-11-02_1047.zip", false, false, "nor their contents"},
		{"libraries", true, false, "re-downloaded on start"},
		{"libraries/com/foo/bar.jar", false, false, "likewise"},
		{"versions", true, false, "re-downloaded on start"},
		{"cache", true, false, "rebuilt"},
		{"logs", true, false, "noise"},
		{"logs/latest.log", false, false, "noise"},
		{"crash-reports", true, false, "noise"},

		// Unknown junk at the root is not swept in.
		{"start.bat", false, false, "regenerated by mcinit new"},
		{"eula.txt", false, false, "regenerated by mcinit new"},
		{"boot.log", false, false, "not ours"},
		{"random-folder", true, false, "not opted into"},
		{"random-folder/file.txt", false, false, "not opted into"},

		{".", true, false, "the root itself is not an entry"},
	}

	for _, tt := range tests {
		if got := s.Include(tt.rel, tt.isDir); got != tt.want {
			t.Errorf("Include(%q, dir=%v) = %v, want %v — %s", tt.rel, tt.isDir, got, tt.want, tt.why)
		}
	}
}

func TestIncludeFollowsLevelName(t *testing.T) {
	// A server with a custom level-name keeps its own three directories and
	// not the default ones.
	s := NewSelection(server.Info{LevelName: "survival"})

	included := []string{"survival", "survival/level.dat", "survival_nether", "survival_the_end"}
	for _, rel := range included {
		if !s.Include(rel, false) {
			t.Errorf("Include(%q) = false, want true for level-name=survival", rel)
		}
	}
	for _, rel := range []string{"world", "world/level.dat", "world_nether"} {
		if s.Include(rel, false) {
			t.Errorf("Include(%q) = true, but level-name is survival", rel)
		}
	}
}

func TestIncludeAcceptsWindowsSeparators(t *testing.T) {
	// filepath.Walk hands back backslashes on Windows; zip entries use forward
	// slashes. The rules must not care which arrives.
	s := defaultSelection()
	if !s.Include(`world\region\r.0.0.mca`, false) {
		t.Error("a backslash path was rejected")
	}
	if s.Include(`logs\latest.log`, false) {
		t.Error("a backslash path escaped the skip list")
	}
}

// TestIncludeSkipsToolCaches covers what a real Paper server turned up: a
// regenerable remap cache inside plugins/ that was larger than the world, and
// mcinit's own restore staging directory. Both hide behind dot names.
func TestIncludeSkipsToolCaches(t *testing.T) {
	s := defaultSelection()

	skipped := []string{
		"plugins/.paper-remapped",
		"plugins/.paper-remapped/index.json",
		"plugins/.paper-remapped/remap-classpath/abc.jar",
		"plugins/.paper-remapped/mappings/reversed/abc.tiny",
		".mcinit-restore-123456",
		".mcinit-restore-123456/world/level.dat",
		"world/.cache/thing",
	}
	for _, rel := range skipped {
		if s.Include(rel, false) {
			t.Errorf("Include(%q) = true; dot directories are tool internals", rel)
		}
	}

	// Real plugin data must still come along.
	kept := []string{
		"plugins/bStats/config.yml",
		"plugins/spark/config.json",
		"plugins/EssentialsX.jar",
		"config/paper-global.yml",
	}
	for _, rel := range kept {
		if !s.Include(rel, false) {
			t.Errorf("Include(%q) = false; this is real plugin or server data", rel)
		}
	}
}
